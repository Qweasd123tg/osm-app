#!/usr/bin/env python3
"""Extract the generated shade demo into the Android asset bundle."""

from __future__ import annotations

import argparse
import json
from pathlib import Path


DEFAULT_OUTPUT = Path("app/src/main/assets/map-data.js")
REGION = {
    "name": "Московская, Санкт-Петербург",
    "center": [30.3229, 59.8521],
    "bounds": [[30.3100, 59.8458], [30.3358, 59.8584]],
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Build map-data.js from shade-map-3d HTML output."
    )
    parser.add_argument(
        "--source",
        type=Path,
        required=True,
        help="Path to a generated 3d.html file.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help=f"Output path (default: {DEFAULT_OUTPUT}).",
    )
    return parser.parse_args()


def extract_json_assignment(source: str, variable: str) -> object:
    marker = f"const {variable} = "
    start = source.find(marker)
    if start < 0:
        raise ValueError(f"Could not find {variable!r} in source HTML")
    payload = source[start + len(marker) :]
    value, _ = json.JSONDecoder().raw_decode(payload)
    return value


def json_for_javascript(value: object) -> str:
    return (
        json.dumps(value, ensure_ascii=False, separators=(",", ":"))
        .replace("&", "\\u0026")
        .replace("<", "\\u003c")
        .replace(">", "\\u003e")
    )


def main() -> None:
    args = parse_args()
    source = args.source.read_text(encoding="utf-8")
    buildings = extract_json_assignment(source, "buildings")
    frames = extract_json_assignment(source, "shadeFrames")

    if not isinstance(buildings, dict) or buildings.get("type") != "FeatureCollection":
        raise ValueError("buildings must be a GeoJSON FeatureCollection")
    if not isinstance(frames, list) or not frames:
        raise ValueError("shadeFrames must be a non-empty list")

    bundle = {
        "region": REGION,
        "buildings": buildings,
        "shadeFrames": frames,
    }
    rendered = (
        "// Generated by tools/build_map_data.py; do not edit by hand.\n"
        f"window.SLOI_MAP_DATA = {json_for_javascript(bundle)};\n"
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="utf-8")
    print(
        f"Wrote {args.output}: {len(buildings['features'])} buildings, "
        f"{len(frames)} time frames"
    )


if __name__ == "__main__":
    main()
