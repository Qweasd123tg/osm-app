import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const root = new URL('../app/src/main/assets/', import.meta.url);
const sandbox = { window: {}, TextEncoder, AbortController, URL, URLSearchParams, setTimeout, clearTimeout };
vm.createContext(sandbox);
for (const file of ['modules/live-transport.js', 'transport-presets.js']) vm.runInContext(fs.readFileSync(new URL(file, root), 'utf8'), sandbox);
const { create, storageKey, maxPresets } = sandbox.window.SloiTransportPresets;
const plain = x => JSON.parse(JSON.stringify(x));
const storage = { value: null, getItem(key) { assert.equal(key, storageKey); return this.value; }, setItem(key, value) { assert.equal(key, storageKey); this.value = value; } };
const routes = [{ type: 'bus', number: ' 49 ', color: '#FF1234' }, { type: 'tram', number: '49', color: '#44AA22' }];
const applied = [], store = create({ storage, onSelect: async (routes, context) => applied.push({ routes, current: context.isCurrent() }) });
let changes = 0; const unsubscribe = store.subscribe(() => changes++);
const first = store.save({ name: ' На работу ', routes });
assert.equal(first.name, 'На работу');
assert.deepEqual(plain(first.routes), [{ type: 'bus', number: '49', color: '#ff1234' }, { type: 'tram', number: '49', color: '#44aa22' }]);
assert.equal(applied.length, 0, 'Saving the collection does not implicitly change the map');
first.routes[0].number = '999';
assert.equal(store.list()[0].routes[0].number, '49', 'Caller cannot mutate stored routes');
await store.select(first.id);
assert.equal(store.activeId(), first.id); assert.equal(applied.length, 1); assert(applied[0].current);
const restored = create({ storage });
assert.equal(restored.activeId(), first.id); assert.equal(restored.list()[0].routes[0].number, '49');
const edited = store.save({ id: first.id, name: 'Домой', routes: [{ type: 'trolley', number: '17', color: '#123456' }] });
assert.equal(store.list().length, 1); assert.equal(store.activeId(), edited.id);
const before = storage.value;
for (const value of [{name:'',routes}, {name:'x',routes:[]}, {name:'x',routes:[...routes,routes[0]]}, {id:'missing',name:'x',routes}, {name:'x',routes:[{type:'bus',number:'49',color:'red'}]}]) assert.throws(() => store.save(value));
assert.equal(storage.value, before);
await assert.rejects(store.select('missing'));
assert.equal(store.activeId(), edited.id);
const write = storage.setItem;
storage.setItem = () => { throw new Error('quota'); };
assert.throws(() => store.save({name:'lost',routes}), /сохранить/);
assert.throws(() => store.remove(edited.id), /сохранить/);
await assert.rejects(store.select(null), /сохранить/);
assert.equal(store.list()[0].name, 'Домой'); assert.equal(store.activeId(), edited.id);
storage.setItem = write;
store.clearActive(); assert.equal(store.activeId(), null); assert.equal(applied.length, 1);
await store.select(null); assert.equal(applied[1].routes, null);
store.remove(edited.id); assert.equal(store.list().length, 0);
unsubscribe(); const count = changes; store.save({ name:'После отписки', routes }); assert.equal(changes, count);
assert(create({storage:{getItem:()=>'{bad'}}).warning());
assert(create({storage:{getItem:()=>JSON.stringify({version:99,presets:[]})}}).warning());
assert(create({storage:{getItem:()=>JSON.stringify({version:1,presets:[{id:'same',name:'x',routes},{id:'same',name:'x',routes}]})}}).warning());
const limited = create({ storage: { getItem:()=>null, setItem(){} } });
for (let i=0;i<maxPresets;i++) limited.save({name:`Набор ${i}`, routes});
assert.throws(()=>limited.save({name:'over', routes}), /20/);
// Completion of an older async selection must not re-enable or overwrite a newer one.
let oldContext, resolveOld;
const racing = create({storage:{getItem:()=>null,setItem(){}}, onSelect:async (routes,ctx)=>{if(routes){oldContext=ctx;await new Promise(r=>resolveOld=r);}}});
const saved = racing.save({name:'old', routes});
const pending = racing.select(saved.id); await racing.select(null);
assert.equal(oldContext.isCurrent(), false); resolveOld(); await pending; assert.equal(racing.activeId(), null);
console.log('Transport presets OK: persistence/reload, typed numbers/colors, edit/delete, bounds, failed-write atomicity and async selection ownership');
